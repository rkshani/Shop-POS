/** Simple positional formatting — avoids pulling a platform formatter into common code. */
fun String.fmt(vararg args: String): String {
    var result = this
    args.forEachIndexed { index, value ->
        result = result.replace("%${index + 1}\$s", value)
    }
    if (args.size == 1) result = result.replace("%s", args[0])
    return result
}
